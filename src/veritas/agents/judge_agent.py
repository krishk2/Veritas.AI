from typing import Dict, Any, List
import os
from veritas.core.llm import get_agent_llm
from langchain_core.prompts import ChatPromptTemplate
from langchain_core.output_parsers import JsonOutputParser
from veritas.core.state import AgentState
from dotenv import load_dotenv

load_dotenv()

def judge_agent(state: AgentState) -> Dict[str, Any]:
    """
    JudgeAgent: Produces a final verdict with Perplexity-style inline source citations [1], [2]
    based on multimodal textual and visual evidence using Gemini.
    """
    print("---JudgeAgent---")
    claim = state["claim"]
    evidence = state.get("evidence", []) or []
    image_forensics = state.get("image_forensics", {}) or {}
    video_forensics = state.get("video_forensics", {}) or {}
    visual_evidence = state.get("visual_evidence", []) or []
    sources = state.get("sources", []) or []

    print(f"Judging claim '{claim}' based on {len(evidence)} pieces of evidence and {len(sources)} sources.")

    # 1. Build visual forensics briefing
    visual_briefing_lines = []
    if image_forensics.get("has_image"):
        visual_briefing_lines.append(f"Image Forensic Summary: {image_forensics.get('summary', 'No summary')}")
        va = image_forensics.get("visual_analysis")
        if va:
            visual_briefing_lines.append(f"Multimodal Visual Depiction: {va.get('description', '')}")
            visual_briefing_lines.append(f"Visual Alignment to Claim: {va.get('alignment', '')} (Confidence: {va.get('confidence', '')})")
            visual_briefing_lines.append(f"Visual Corroboration Finding: {va.get('finding', '')}")
            if va.get("detected_text"):
                visual_briefing_lines.append(f"Visible Embedded Text/Captions: '{va.get('detected_text')}'")
        if image_forensics.get("ai_generation_detected"):
            visual_briefing_lines.append(f"CRITICAL: Image was generated by AI ({', '.join(image_forensics.get('ai_markers', []))}).")
        if image_forensics.get("tampering_indicators"):
            visual_briefing_lines.append(f"Tampering Alerts: {'; '.join(image_forensics.get('tampering_indicators', []))}")
        if image_forensics.get("ela_score", 0.0) > 0.8:
            visual_briefing_lines.append(f"High compression/splicing anomaly score: {image_forensics.get('ela_score')}")
    else:
        visual_briefing_lines.append("No image media provided with this claim.")

    if video_forensics.get("has_video"):
        visual_briefing_lines.append(f"Video Forensic Summary: {video_forensics.get('summary', 'No summary')}")
        if video_forensics.get("is_deepfake_or_ai"):
            combined_markers = video_forensics.get("ai_video_markers", []) + video_forensics.get("deepfake_indicators", [])
            visual_briefing_lines.append(f"CRITICAL: Video is identified as a DEEPFAKE or AI-GENERATED VIDEO ({', '.join(combined_markers)}).")

    for ve in visual_evidence:
        visual_briefing_lines.append(f"Visual Provenance: {ve.get('sentence')}")

    visual_context = "\n".join(visual_briefing_lines)

    # 2. Build numbered source reference list for Perplexity-style citations
    numbered_sources = []
    for idx, s in enumerate(sources, start=1):
        title = s.get("title", f"Source {idx}")
        url = s.get("url", "")
        snippet = s.get("content", "")[:280]
        numbered_sources.append(f"[{idx}] {title} - {url}\n    Excerpt: {snippet}")

    sources_reference_text = "\n\n".join(numbered_sources) if numbered_sources else "No web sources indexed."

    try:
        llm = get_agent_llm("judge_agent", temperature=0)
        
        prompt_text = """
        You are an impartial, authoritative fact-checking judge and investigative journalist.
        You have both textual web evidence with numbered citations and multimodal forensic analysis.
        
        Claim:
        {claim}
        
        Multimodal Visual Context & Forensics:
        {visual_context}
        
        Available Sources for Citation:
        {sources_reference}
        
        Evidence Gathered:
        {evidence}
        
        Instructions:
        1. Determine if the claim is TRUE, FALSE, or UNCLEAR.
        2. Write a clear, comprehensive 2-3 paragraph explanation in the signature style of PERPLEXITY AI:
           - You MUST provide inline bracketed numeric citations (e.g. [1], [2], [1, 2]) matching the Available Sources for EVERY factual claim, quote, or refutation made.
           - Every major point in your explanation must be directly attributable to a citation.
        3. If attached visual media has been provided, actively factor what is depicted into your judgment. State whether the visual scene genuinely supports, contradicts, or is misattributed/recycled, and synthesize visual evidence into your reasoning.
        4. Provide a confidence score (0.0 to 1.0) and an objective cited explanation.
        
        Return the output as a JSON object with keys: "verdict", "confidence", "explanation".
        """
        
        prompt = ChatPromptTemplate.from_template(prompt_text)
        chain = prompt | llm | JsonOutputParser()
        
        if evidence:
            evidence_text = "\n".join([f"- [{e.get('source', 'evidence')}] {e.get('label', 'INFO')} ({e.get('score', 0.5)}): {e.get('sentence', '')}" for e in evidence])
        else:
            evidence_text = "No direct evidence passages available."
        
        result = chain.invoke({
            "claim": claim,
            "visual_context": visual_context,
            "sources_reference": sources_reference_text,
            "evidence": evidence_text
        })
        
        return {
            "verdict": result.get("verdict", "UNCLEAR"),
            "confidence": float(result.get("confidence", 0.0)),
            "explanation": result.get("explanation", "No explanation provided.")
        }
        
    except Exception as e:
        print(f"Error in JudgeAgent: {e}")
        # Fallback heuristic if LLM is unavailable:
        if video_forensics.get("is_deepfake_or_ai"):
            return {
                "verdict": "FALSE",
                "confidence": video_forensics.get("confidence", 0.90),
                "explanation": f"Automated video forensic check detected synthetic AI generation or deepfake manipulation [1]: {video_forensics.get('summary')}."
            }
        if image_forensics.get("is_tampered_or_ai"):
            return {
                "verdict": "FALSE",
                "confidence": 0.85,
                "explanation": f"Automated forensic check detected visual tampering or AI generation [1]: {image_forensics.get('summary')}."
            }
        return {
            "verdict": "UNCLEAR",
            "confidence": 0.0,
            "explanation": f"Error during judgment: {e}"
        }
